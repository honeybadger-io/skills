"""Snapshot the get_reference topics from the docs site into the eval mocks.

The MCP server's get_reference fetches these topics from the docs site at
runtime. The evals serve a committed snapshot instead, so a docs change shows
up as a diff here rather than silently changing eval results.

A mock can't choose its reply by input, and a case's mock can't read the
suite's fixtures, so each case in CASE_TOPICS gets a get_reference mock with
its topics written in, composed the way the server composes them.

    python3 -I evals/refresh_references.py          # download the current topics
    python3 -I evals/refresh_references.py --check  # list topics that changed since the snapshot
"""

import hashlib
import json
import pathlib
import sys
import urllib.request

BASE_URL = "https://docs.honeybadger.io/resources/llms/instructions"
EVALS = pathlib.Path(__file__).resolve().parent
SNAPSHOT = EVALS / "mocks" / "honeybadger" / "fixtures" / "reference"

# The topics create_dashboard and update_dashboard require.
DASHBOARD_TOPICS = ["dashboards", "charts", "queries", "badgerql"]
CASE_TOPICS = {
    "dash-add-widget": DASHBOARD_TOPICS,
    "dash-empty-widget": DASHBOARD_TOPICS,
    "dash-new-dashboard": DASHBOARD_TOPICS,
    "dash-undo": DASHBOARD_TOPICS,
}
USED_TOPICS = {name for topics in CASE_TOPICS.values() for name in topics}


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read()


def live_hashes():
    return {t["name"]: t["sha256"] for t in json.loads(fetch(f"{BASE_URL}/index.json"))["instructions"]}


def snapshot_hashes():
    path = SNAPSHOT / "index.json"
    if not path.exists():
        return {}
    return {t["name"]: t["sha256"] for t in json.loads(path.read_text())["instructions"]}


def check():
    saved, live = snapshot_hashes(), live_hashes()
    missing = sorted(USED_TOPICS - live.keys())
    if missing:
        print("the docs index has no " + ", ".join(missing) + " topic; the evals still serve the old snapshot")
        return 1
    changed = sorted(name for name in USED_TOPICS if saved.get(name) != live.get(name))
    if not changed:
        print("reference snapshot matches the docs site")
        return 0
    print("reference topics changed since the snapshot: " + ", ".join(changed))
    print("run python3 -I evals/refresh_references.py, then re-run the evals")
    return 1


def refresh():
    index = json.loads(fetch(f"{BASE_URL}/index.json"))
    topics = [t for t in index["instructions"] if t["name"] in USED_TOPICS]
    missing = USED_TOPICS - {t["name"] for t in topics}
    if missing:
        sys.exit(f"the docs index has no {', '.join(sorted(missing))} topic; nothing written")
    bodies = {}
    for topic in topics:
        body = fetch(topic["url"])
        digest = hashlib.sha256(body).hexdigest()
        if digest != topic["sha256"]:
            sys.exit(f"{topic['name']}: downloaded sha256 {digest} does not match the index's {topic['sha256']}; nothing written")
        bodies[topic["name"]] = body
    # Write only once every topic has downloaded and matched, so a failed run leaves the old snapshot whole.
    SNAPSHOT.mkdir(parents=True, exist_ok=True)
    for old in SNAPSHOT.glob("*.txt"):
        old.unlink()
    for name, body in bodies.items():
        (SNAPSHOT / f"{name}.txt").write_bytes(body)
        print(f"{name}: {len(body)} bytes")
    (SNAPSHOT / "index.json").write_text(json.dumps({"instructions": topics}, indent=2) + "\n")
    order = [t["name"] for t in topics]
    for case, case_topics in CASE_TOPICS.items():
        write_case_mock(case, [name for name in order if name in case_topics])
    return 0


def write_case_mock(case, topics):
    """Compose the topics as the server does: in index order, joined by a rule."""
    body = "\n\n---\n\n".join((SNAPSHOT / f"{name}.txt").read_text() for name in topics)
    header = f"---\n# Generated by evals/refresh_references.py from the topics {', '.join(topics)}. Do not edit.\n---\n\n"
    path = EVALS / case / "mocks" / "honeybadger" / "get_reference.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + body)
    print(f"{case}: get_reference serves {', '.join(topics)} ({len(body)} bytes)")


if __name__ == "__main__":
    sys.exit(check() if sys.argv[1:] == ["--check"] else refresh())
